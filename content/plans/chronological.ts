// Chronological reading order: ranges only. Whole chapters; `v` omitted = whole chapter.

export interface ChronoRange {
  book: string;
  from: { c: number; v?: number };
  to: { c: number; v?: number };
}

const r = (book: string, from: number, to: number = from): ChronoRange => ({ book, from: { c: from }, to: { c: to } });
const ps = (...chapters: number[]): ChronoRange[] => chapters.map((c) => r("PSA", c));

