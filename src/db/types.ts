// Data model for Abide. Mirrors the spec; Settings and Streak are singletons (id = "singleton").

export type TranslationId = "BSB" | "WEB" | "KJV" | "ESV";
export type BookCode = string; // "GEN".."REV"
export interface VerseRef { book: BookCode; chapter: number; verse: number }
export interface VerseRange { start: VerseRef; end: VerseRef }
export type VerseKey = string; // "ROM.8.28"

export interface MemoryPlan {
  id: string; title: string; translation: TranslationId; range: VerseRange;
  chunks: VerseKey[][]; chunksIntroduced: number; pace: "daily" | "everyOtherDay" | "twicePerDay";
  status: "active" | "paused" | "mastered"; starterId?: string; createdAt: number; updatedAt: number;
  /** Date (YYYY-MM-DD) of the first day; new chunks are introduced from this date on. */
  startDate?: string;
  /** ms timestamp of the most recent chunk introduction (pace bookkeeping). */
  lastIntroducedAt?: number;
}
export interface SrsState { stability: number; difficulty: number; due: number; reps: number; lapses: number; lastReviewed?: number }
export interface VerseCard extends SrsState { id: string; planId: string; key: VerseKey; updatedAt: number }
export interface PassageCard extends SrsState { id: string; planId: string; updatedAt: number }
export type PracticeMode = "read" | "hide" | "firstLetters" | "typeFirst" | "recall" | "speak" | "reference" | "handsFree" | "headings";
export interface ReviewLog {
  id: string; cardId: string; cardType: "verse" | "passage"; mode: PracticeMode;
  grade: 1 | 2 | 3 | 4 | 5; accuracy: number; durationMs: number; at: number;
  /** true for Hands-Free "heard" logs: not graded, card stays due. */
  heard?: boolean;
}
export interface BsbHeading { book: BookCode; chapter: number; verse: number; level: "s1" | "s2" | "ms" | "d"; text: string }

// ---- Sourced context (generated by scripts; read-only in app) ----
export type Era = "early" | "medievalReformation" | "puritan18c" | "c19" | "c20early" | "modern";
export type SourceType = "commentary" | "sermon" | "apologetics" | "theology" | "confession" | "catechism" | "devotional" | "crossref";
export type ParserId = "ccel-txt" | "verse-commentary" | "heading-range" | "inline-citation" | "creed-json-proofs" | "html-chapters" | "openbible-crossrefs";
export interface SourceWork {
  id: string; author: string; title: string; edition: string; // e.g. "NPNF1-02, trans. Dods"
  era: Era; types: SourceType[]; sourcePage: string; rawUrls: string[]; rawSha256: string[];
  license: {
    status: "public-domain" | "CC-BY"; proofUrl: string; proofText: string;
    basis: "rights-statement" | "published-before-1931" | "pd-mark" | "cc-by";
  };
  parser: ParserId;
  parserOptions?: Record<string, unknown>; defaultEnabled: boolean; largePack: boolean; packSizeBytes: number; ocr?: boolean;
}
export interface Excerpt {
  id: string; workId: string; text: string; // verbatim
  locator: string;            // "Book XIV, ch. 28" | "Homily XV" | "Ps 23:1, Exposition" | "Q. 1" | "p. 212"
  url: string;                // deep link if derivable, else work page
  verseRanges: VerseRange[];  // from the work's own citation/heading/index
  mappingMethod: "heading" | "scriptureIndex" | "inlineCitation" | "proofText" | "sermonText" | "entryVerse";
  type: SourceType; era: Era; charOffset: number; verbatimHash: string; isBookIntro?: boolean;
  /** Index into SourceWork.rawUrls of the file charOffset refers to. */
  rawIndex: number;
  /** true when the excerpt was cut short of its paragraph; the UI renders "…" outside the verbatim text. */
  truncatedEnd?: boolean; truncatedStart?: boolean;
  /** id of the full (also verified) section excerpt, for "Read full section". */
  sectionId?: string;
}
export interface CrossRef { from: VerseKey; to: VerseRange; votes: number }

// ---- User content ----
export interface BookPlan {
  id: string; title: string; author: string; edition?: string;
  unit: "pages" | "chapters" | "sections"; total: number; current: number; startDate: string; targetDate: string;
  classicId?: string; dateLocked?: boolean; status: "active" | "finished" | "paused"; updatedAt: number;
  /** Optional alternative to targetDate: fixed units per reading day. */
  unitsPerDay?: number;
}
export interface BookLog { id: string; bookId: string; date: string; from: number; to: number; updatedAt?: number }
export interface UserNote {
  id: string; kind: "quote" | "note"; bookId?: string; page?: string; text: string;
  verseRanges: VerseRange[]; createdAt: number; updatedAt: number;
  /** Derived: every VerseKey covered by verseRanges (multi-entry index). */
  verseKeys: VerseKey[];
} // shown as "from my reading"
export interface LinkOut {
  id: string; url: string; title: string; author?: string; site: string;
  statedReference: string;    // as written on the page, entered/confirmed by me
  /** true when the page itself states no reference and I typed it from the content. */
  referenceEnteredByMe?: boolean;
  verseRanges: VerseRange[]; createdAt: number; updatedAt: number;
  verseKeys: VerseKey[];
}
export type ReadingStyle = "canonical" | "chronological" | "blended";
export interface ReadingPlan {
  id: string; style: ReadingStyle; translation: TranslationId; startDate: string;
  graceWeekday: 0 | 1 | 2 | 3 | 4 | 5 | 6; totalDays: 312; missedPolicy: "ask" | "spread" | "shiftEnd" | "graceDay";
  createdAt: number; updatedAt: number;
}
export interface ReadingPortion { track: "OT" | "NT" | "PP" | "ALL"; range: VerseRange; verseCount: number; done: boolean; doneAt?: number }
export interface ReadingDay { id: string; planId: string; dayIndex: number; date: string; portions: ReadingPortion[]; updatedAt?: number }

export type Theme = "system" | "light" | "dark" | "sunlight";
export interface Settings {
  id: "singleton";
  translation: TranslationId; fontScale: number; theme: Theme;
  ttsVoice?: string; ttsRate: number; handsFreePauseSec: number; reminderTime: string; // "HH:MM"
  graceWeekday: 0 | 1 | 2 | 3 | 4 | 5 | 6; readingVersesPerMin: number; enabledPacks: string[];
  esvKey?: string; esvEnabled?: boolean; lastBackupAt?: number; dailyNewLimit: number; updatedAt: number;
}
export interface Streak { id: "singleton"; current: number; best: number; lastActiveDate?: string; activeDates: string[]; updatedAt: number }

export interface LibraryCacheEntry { id: string /* `${packId}/${BOOK}` */; packId: string; book: BookCode; data: unknown; fetchedAt: number }
